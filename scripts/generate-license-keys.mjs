/**
 * Run ONCE:   node scripts/generate-license-keys.mjs
 *
 * 1. Creates an ECDSA P-256 key pair.
 * 2. Writes the PUBLIC key into src/config/licensePublicKey.ts  (commit this file).
 * 3. Prints the PRIVATE key → paste it into Vercel as LICENSE_SIGNING_KEY (Production).
 *    Never commit / share the private key. If it leaks, run the script again and redeploy:
 *    old codes stop working and customers get new ones at their next renewal.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'src', 'config', 'licensePublicKey.ts');

const { publicKey, privateKey } = crypto.generateKeyPairSync('ec', { namedCurve: 'P-256' });
const jwk = publicKey.export({ format: 'jwk' });
const privateB64 = privateKey.export({ format: 'der', type: 'pkcs8' }).toString('base64');

const file = `// Generated by scripts/generate-license-keys.mjs on ${new Date().toISOString()}
// PUBLIC key only — safe to commit. The private key lives ONLY in Vercel (LICENSE_SIGNING_KEY).
export const LICENSE_PUBLIC_KEY_JWK: JsonWebKey | null = ${JSON.stringify(
  { kty: jwk.kty, crv: jwk.crv, x: jwk.x, y: jwk.y },
  null,
  2
)};
`;
fs.writeFileSync(target, file, 'utf-8');

console.log('✅ Public key written to src/config/licensePublicKey.ts (commit it).');
console.log('');
console.log('🔐 Vercel → Settings → Environment Variables → Production:');
console.log('   Name : LICENSE_SIGNING_KEY');
console.log('   Value:');
console.log(privateB64);
console.log('');
console.log('⚠️  Do NOT commit or share the value above.');
